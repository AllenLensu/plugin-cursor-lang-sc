export function loadNls() {
  const keyGroups = readJson(paths.nlsKeys);
  const messages = readJson(paths.nlsMessages);
  if (!Array.isArray(keyGroups) || !Array.isArray(messages)) {
    throw new Error("nls.keys.json and nls.messages.json must be arrays");
  }
  const modules = {};
  const order = [];
  const duplicates = [];
  let index = 0;
  for (const group of keyGroups) {
    if (!Array.isArray(group) || group.length !== 2 || !Array.isArray(group[1])) {
      throw new Error("unexpected nls.keys.json group");
    }
    const [mod, keys] = group;
    if (!Object.prototype.hasOwnProperty.call(modules, mod)) {
      modules[mod] = {};
      order.push(mod);
    }
    const bag = modules[mod];
    for (const key of keys) {
      if (index >= messages.length) {
        throw new Error("nls.messages.json is shorter than nls.keys.json");
      }
      const english = messages[index++];
      if (typeof english !== "string") {
        throw new Error(`message ${index - 1} in ${mod}#${key} is not a string`);
      }
      if (Object.prototype.hasOwnProperty.call(bag, key)) {
        if (bag[key] !== english) duplicates.push({ module: mod, key, english });
        continue;
      }
      bag[key] = english;
    }
  }
  if (index !== messages.length) {
    throw new Error(`nls.messages.json has ${messages.length - index} unused messages`);
  }
  let uniqueKeys = 0;
  for (const bag of Object.values(modules)) uniqueKeys += Object.keys(bag).length;
  return { modules, order, keyCount: uniqueKeys, messageCount: index, duplicates };
}

