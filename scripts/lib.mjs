export function loadOverlays() {
  const dir = path.join(root, "src", "zh-cn");
  const overlays = [];
  if (!fs.existsSync(dir)) return overlays;
  const files = [];
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith(".json")) files.push(full);
    }
  };
  walk(dir);
  files.sort();
  for (const file of files) {
    const json = readJson(file);
    if (json.contents && typeof json.contents === "object") {
      overlays.push({ file, contents: json.contents });
    } else {
      overlays.push({ file, contents: json });
    }
  }
  return overlays;
}

export function extractTokens(value) {
  return {
    placeholders: [...value.matchAll(/\{\d+\}/g)].map((match) => match[0]),
    icons: [...value.matchAll(/\$\([^)\r\n]+\)/g)].map((match) => match[0]),
    commands: [...value.matchAll(/\(command:[^)\r\n]+\)/g)].map((match) => match[0]),
  };
}

export function sameTokens(english, chinese) {
  const left = extractTokens(english);
  const right = extractTokens(chinese);
  return (
    sameMultiset(left.placeholders, right.placeholders) &&
    sameMultiset(left.icons, right.icons) &&
    sameMultiset(left.commands, right.commands)
  );
}

function sameMultiset(left, right) {
  if (left.length !== right.length) return false;
  const a = [...left].sort();
  const b = [...right].sort();
  return a.every((item, index) => item === b[index]);
}

const PRODUCT_NAMES = ["Cursor", "MCP", "Claude", "Codex", "Copilot", "Composer", "Glass"];
const AGENT_GUARDS = ["代理服务器", "网络代理", "系统代理", "HTTP 代理", "HTTPS 代理"];

/**
 * Adjust a reused VS Code string when its English uses Cursor's glossary.
 * Agent/Agents replace VS Code's 代理. Product names and the caret word Cursor
 * are not rewritten here: 光标 stays 光标 until you say otherwise.
 */
export function applyGlossary(english, chinese) {
  if (!/\bAgents?\b/.test(english) || chinese.includes("智能体")) return chinese;
  let next = chinese;
  for (const guard of AGENT_GUARDS) next = next.split(guard).join(`\u0000${guard}\u0000`);
  next = next.split("代理").join("智能体");
  for (const guard of AGENT_GUARDS) next = next.split(`\u0000${guard}\u0000`).join(guard);
  return next;
}

export function hasGlossaryWord(english) {
  return /\b(Agents?|Chat|Cursor|MCP|Claude|Codex|Copilot|Composer|Glass)\b/.test(english);
}

/**
 * A baseline pair can seed same-key or same-English reuse only when the
 * Chinese still matches this English. Stale keys (English changed, old
 * translation left in place) and keys with two different English strings
 * must not be copied onto other keys.
 */
export function canSeedReuse(english, chinese) {
  if (!sameTokens(english, chinese)) return false;
  if (/\bAgents?\b/.test(english) && !chinese.includes("智能体")) return false;
  if (/\bChat\b/.test(english) && !chinese.includes("聊天")) return false;
  for (const name of PRODUCT_NAMES) {
    if (new RegExp(`\\b${name}\\b`).test(english) && !chinese.includes(name)) return false;
  }
  return true;
}

export function buildIndexes(snapshot, upstream) {
  const blocked = new Set((snapshot.duplicates ?? []).map((item) => `${item.module}\0${item.key}`));
  const byKey = new Map();
  const byEnglish = new Map();
  for (const [mod, bag] of Object.entries(snapshot.modules)) {
    for (const [key, english] of Object.entries(bag)) {
      const chinese = upstream[mod]?.[key];
      if (typeof chinese !== "string") continue;
      if (blocked.has(`${mod}\0${key}`)) continue;
      if (!canSeedReuse(english, chinese)) continue;
      if (!byKey.has(key)) byKey.set(key, []);
      byKey.get(key).push({ mod, english, chinese });
      const norm = normWs(english);
      if (!byEnglish.has(norm)) byEnglish.set(norm, new Map());
      const bucket = byEnglish.get(norm);
      if (!bucket.has(chinese)) {
        bucket.set(chinese, { count: 0, mod, key });
      }
      bucket.get(chinese).count += 1;
    }
  }
  return { byKey, byEnglish };
}

export function candidatesFor(byEnglish, english) {
  const bucket = byEnglish.get(normWs(english));
  if (!bucket) return [];
  return [...bucket.entries()]
    .map(([chinese, info]) => ({
      chinese,
      count: info.count,
      example: { module: info.mod, key: info.key },
    }))
    .sort((a, b) => b.count - a.count || a.chinese.localeCompare(b.chinese, "zh"));
}

export function multiEnglishKeyIds(snapshot) {
  const ids = new Set();
  for (const dup of snapshot.duplicates ?? []) {
    const primary = snapshot.modules[dup.module]?.[dup.key];
    if (primary !== dup.english) ids.add(`${dup.module}\0${dup.key}`);
  }
  return ids;
}

export function resolveCore(snapshot, upstream) {
  const { byKey, byEnglish } = buildIndexes(snapshot, upstream);
  const omittedIds = multiEnglishKeyIds(snapshot);
  const resolved = new Map();
  const unmatched = [];
  const omitted = [];
  const stats = {
    baseline: 0,
    sameKey: 0,
    englishText: 0,
    authored: 0,
    unmatched: 0,
    omitted: 0,
    glossary: 0,
  };

  for (const mod of snapshot.order) {
    for (const [key, english] of Object.entries(snapshot.modules[mod])) {
      const id = `${mod}\0${key}`;
      if (omittedIds.has(id)) {
        const variants = [english];
        for (const dup of snapshot.duplicates ?? []) {
          if (dup.module === mod && dup.key === key && !variants.includes(dup.english)) variants.push(dup.english);
        }
        omitted.push({ module: mod, key, english, variants });
        stats.omitted += 1;
        continue;
      }
      const direct = upstream[mod]?.[key];
      if (typeof direct === "string") {
        const chinese = applyGlossary(english, direct);
        resolved.set(id, { chinese, raw: direct, source: "baseline", mod, key, english });
        stats.baseline += 1;
        if (chinese !== direct) stats.glossary += 1;
        continue;
      }

      const siblings = (byKey.get(key) ?? []).filter((item) => item.english === english && canSeedReuse(item.english, item.chinese));
      const distinct = [...new Set(siblings.map((item) => item.chinese))];
      if (distinct.length === 1) {
        const chinese = applyGlossary(english, distinct[0]);
        resolved.set(id, { chinese, raw: distinct[0], source: "sameKey", mod, key, english });
        stats.sameKey += 1;
        if (chinese !== distinct[0]) stats.glossary += 1;
        continue;
      }

      const candidates = candidatesFor(byEnglish, english);
      if (distinct.length === 0 && candidates.length === 1) {
        const chinese = applyGlossary(english, candidates[0].chinese);
        resolved.set(id, { chinese, raw: candidates[0].chinese, source: "englishText", mod, key, english });
        stats.englishText += 1;
        if (chinese !== candidates[0].chinese) stats.glossary += 1;
        continue;
      }

      stats.unmatched += 1;
      unmatched.push({
        module: mod,
        key,
        english,
        area: areaOf(mod),
        candidates,
      });
    }
  }

  const overlays = loadOverlays();
  for (const overlay of overlays) {
    for (const [mod, bag] of Object.entries(overlay.contents)) {
      if (!bag || typeof bag !== "object" || Array.isArray(bag)) continue;
      for (const [key, chinese] of Object.entries(bag)) {
        if (typeof chinese !== "string") continue;
        if (!snapshot.modules[mod] || !Object.prototype.hasOwnProperty.call(snapshot.modules[mod], key)) {
          continue;
        }
        const id = `${mod}\0${key}`;
        if (omittedIds.has(id)) continue;
        const previous = resolved.get(id);
        resolved.set(id, {
          chinese,
          raw: chinese,
          source: "authored",
          mod,
          key,
          english: snapshot.modules[mod][key],
        });
        if (!previous) {
          stats.unmatched -= 1;
          stats.authored += 1;
        } else if (previous.source !== "authored") {
          stats[previous.source] -= 1;
          stats.authored += 1;
        }
      }
    }
  }

  const stillUnmatched = unmatched.filter((item) => {
    const hit = resolved.get(`${item.module}\0${item.key}`);
    return !hit || hit.source !== "authored";
  });
  stats.unmatched = stillUnmatched.length;

  return { resolved, unmatched: stillUnmatched, omitted, stats, byEnglish };
}

export function resolveExtensions(byEnglish) {
  const translated = [];
  const unmatched = [];
  for (const [id, folder] of CURSOR_EXTENSIONS) {
    const nlsPath = path.join(paths.cursorExtensions, folder, "package.nls.json");
    const manifestPath = path.join(paths.cursorExtensions, folder, "package.json");
    const nls = readJson(nlsPath);
    const manifest = readJson(manifestPath);
    const strings = {};
    for (const [key, english] of Object.entries(nls)) {
      if (typeof english !== "string") continue;
      const referenced = manifest[key] === `%${key}%`;
      const overlayPath = path.join(root, "src", "zh-cn", "extensions", `${id}.json`);
      const overlay = fs.existsSync(overlayPath) ? readJson(overlayPath) : {};
      if (typeof overlay[key] === "string") {
        strings[key] = overlay[key];
        continue;
      }
      const candidates = candidatesFor(byEnglish, english);
      if (candidates.length === 1) {
        strings[key] = applyGlossary(english, candidates[0].chinese);
        continue;
      }
      unmatched.push({
        id,
        folder,
        key,
        english,
        referenced,
        area: "extensions",
        candidates,
      });
    }
    if (Object.keys(strings).length > 0) translated.push({ id, strings });
  }
  return { translated, unmatched };
}
