export function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

export function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(value, null, "\t") + "\n", "utf8");
}

/** Trim and collapse horizontal whitespace. Leave newlines in place. */
export function normWs(value) {
  return value.replace(/\r\n/g, "\n").replace(/[ \t]+/g, " ").trim();
}

export function areaOf(mod) {
  const normalized = mod.replaceAll("\\", "/");
  if (normalized.toLowerCase().includes("glass")) return "glass";
  if (normalized.includes("/services/")) return "services";
  if (normalized.includes("/workbench/")) return "workbench";
  if (normalized.includes("/browser/")) return "browser";
  return "other";
}

